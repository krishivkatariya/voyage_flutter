class Itinerary {
  String id;
  String tripId;
  String title;
  String place;
  String date;
  String startTime;
  String endTime;
  String description;

  Itinerary({
    required this.id,
    required this.tripId,
    required this.title,
    required this.place,
    required this.date,
    required this.startTime,
    required this.endTime,
    required this.description,
  });
}